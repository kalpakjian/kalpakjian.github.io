# -*- coding: utf-8 -*-
"""Stress test: run the extractor against a REAL, production-sized AINews body.

Why a separate script from selftest_extract.py:
  * selftest_extract.py proves *behaviour* on a tiny hand-built body (fast, runs in CI)
  * this file proves *scale* against an actual 200 KB+ issue (slow-ish, opt-in)

The real fixture is generated by _make_real_fixture.py from a saved Gmail
response. If it is missing, this exits 0 with a notice -- CI runs on a fresh
clone and should not fail just because the large fixture is absent.

Usage:
    python tools/ainews/stress_extract.py [fixture.json]

Checks (on real data):
  s1  body is big enough to be the real thing (> 50 KB)
  s2  sponsor / masthead / "View image" / footer do NOT survive
  s3  the five expected section kinds appear
  s4  Reddit container yields sub-sections
  s5  stats are plausible (quantities > 50, headings > 10)
  s6  no line is a lone CR, no triple newline, no zero-width leftovers
"""
import glob
import io
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import extract  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
FAILS = []


def check(name, cond, detail=""):
    print(("PASS  " if cond else "FAIL  ") + name + ("" if cond else "  " + str(detail)))
    if not cond:
        FAILS.append(name)


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else None
    if not path:
        cands = sorted(glob.glob(os.path.join(HERE, "fixtures", "real-*.json")))
        if not cands:
            print("no real fixture found (run _make_real_fixture.py first); skipping")
            return 0
        path = cands[-1]

    with io.open(path, encoding="utf-8") as f:
        raw = json.load(f)
    msg = extract._pick_message(raw)
    body = msg.get("messageText") or ""
    print("fixture: %s\nbody chars: %d" % (os.path.basename(path), len(body)))

    check("s1 body is production-sized", len(body) > 50_000, len(body))

    doc = extract.extract_message(msg)
    all_text = "\n".join(s["text"] for s in doc["sections"])
    subs = [x for s in doc["sections"] for x in (s.get("subsections") or [])]
    keys = {s["key"] for s in doc["sections"]}
    # Real issues separate sub-reddit groups with a rule, so each group becomes
    # its own top-level section; a rule-less body keeps them nested in the
    # container. Accept either shape, but require >= 2 Reddit-derived sections.
    reddit_sections = [s for s in doc["sections"]
                       if s["key"] in ("local", "less_technical") or s.get("subsections")]

    check("s2a sponsor removed", "NODES 2026" not in all_text)
    check("s2b masthead removed", "brought to you by" not in all_text)
    check("s2c image lines removed", "View image:" not in all_text)
    check("s2d footer removed", "reading a plain text version" not in all_text)

    check("s3a lede present", len(doc["lede"]) > 200, len(doc["lede"]))
    check("s3b twitter section", "twitter" in keys, keys)
    check("s3c reddit container", "reddit_container" in keys, keys)

    check("s4 reddit derived sections >= 2", len(reddit_sections) >= 2,
          [s["key"] for s in reddit_sections])
    check("s4a no unclassified reddit section",
          all(s["key"] != "other" for s in reddit_sections),
          [s["key"] for s in reddit_sections])

    st = doc["stats"]
    check("s5a quantities > 50", st["quantities"] > 50, st["quantities"])
    check("s5b headings > 10", st["headings"] > 10, st["headings"])
    check("s5c words > 5000", st["words"] > 5000, st["words"])

    check("s6a no lone CR", not re.search(r"^\\r?$", all_text, re.M))
    check("s6b no triple newline", "\n\n\n" not in all_text)
    check("s6c no zero-width", not any(c in all_text for c in ("\u200b", "\ufeff", "\u2060")))

    print("\nstats: %s" % json.dumps(st, ensure_ascii=False))
    print("\n%s (%d failed)" % ("ALL PASSED" if not FAILS else "FAILURES: " + ", ".join(FAILS), len(FAILS)))
    return 0 if not FAILS else 1


if __name__ == "__main__":
    sys.exit(main())
